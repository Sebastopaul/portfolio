#!/bin/bash
set -e

# variables
CONTAINER_NAME="portfolio-web-front"
LOCAL_DIR="./frontend/node_modules"
REMOTE_DIR="/app/node_modules"

# Couleurs pour l'affichage
GREEN='\033[0;32m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
NC='\033[0m' # reset

printf "${CYAN}Synchronisation du node_modules entre conteneur et local...\n${NC}"

# Si le conteneur n'est pas en cours d'exécution, le créer temporairement
TEMP_CONTAINER=false
if [ "$(docker ps -q -f name=$CONTAINER_NAME)" == "" ]; then
  printf "${YELLOW}Aucun conteneur $CONTAINER_NAME en cours, création temporaire...\n${NC}"
  docker compose build web-front
  docker compose create web-front
  TEMP_CONTAINER=true
fi

# Vérifie que le dossier local existe
mkdir -p "$LOCAL_DIR"

# Liste des modules dans le conteneur
printf "${CYAN}Récupération de la liste des modules...\n${NC}"
docker exec "$CONTAINER_NAME" bash -c "ls $REMOTE_DIR" > /tmp/container_modules.txt

# Liste des modules locaux
ls "$LOCAL_DIR" > /tmp/local_modules.txt 2>/dev/null || true

# Compare les deux listes
MISSING_MODULES=$(comm -23 <(sort /tmp/container_modules.txt) <(sort /tmp/local_modules.txt))

if [ -z "$MISSING_MODULES" ]; then
  printf "${GREEN}Tous les modules sont déjà présents localement.\n${NC}"
else
  printf "${CYAN}Copie des modules manquants :\n${NC}"
  printf "${YELLOW}$MISSING_MODULES\n${NC}"
  for module in $MISSING_MODULES; do
    printf "${CYAN}Copie de $module..."
    docker cp "$CONTAINER_NAME:$REMOTE_DIR/$module" "$LOCAL_DIR/"
  done
  printf "${GREEN}Synchronisation terminée.\n${NC}"
fi

# Nettoyage
rm -f /tmp/container_modules.txt /tmp/local_modules.txt

# Supprime le conteneur temporaire si besoin
if [ "$TEMP_CONTAINER" = true ]; then
  docker rm "$CONTAINER_NAME" > /dev/null
fi